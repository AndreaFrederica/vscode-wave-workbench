import { createHash } from "node:crypto";
import type { BigIntStats } from "node:fs";
import { readFile, realpath, stat } from "node:fs/promises";
import * as path from "node:path";

export interface SimulationManifest {
  schemaVersion: 1;
  filelist: string;
  workingDirectory: string;
  filelists: { path: string; fingerprint: string | null }[];
  sourceFingerprints: SimulationManifest["filelists"];
  libraryMaps?: string[];
  sources: { path: string; sha256?: string }[];
  compilationUnits?: string[][];
  compilationUnitOptions?: { defines?: string[]; include_dirs?: string[] }[];
  libraryFiles: { path: string; sha256?: string }[];
  sourceLibraries?: { path: string; name: string }[];
  resolvedLibraryFiles: string[];
  includeDirectories: string[];
  defines: string[];
  topModules: string[];
  parameterOverrides: string[];
  unverifiedVcsParameterPaths?: string[];
  unsupported: string[];
}

function filelistFingerprint(info: BigIntStats) {
  return [info.dev, info.ino, info.size, info.mtimeNs, info.ctimeNs].join(":");
}

export async function simulationInputFingerprint(filename: string) {
  let fingerprint: string | null;
  try {
    fingerprint = filelistFingerprint(await stat(filename, { bigint: true }));
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code !== "ENOENT") throw error;
    fingerprint = null;
  }
  return { path: filename, fingerprint };
}

export async function simulationFilelistsCurrent(
  entries: SimulationManifest["filelists"],
) {
  for (let offset = 0; offset < entries.length; offset += 64) {
    const current = await Promise.all(
      entries
        .slice(offset, offset + 64)
        .map(
          async (entry) =>
            (await simulationInputFingerprint(entry.path)).fingerprint ===
            entry.fingerprint,
        ),
    );
    if (!current.every(Boolean)) return false;
  }
  return true;
}

function filelistArguments(text: string) {
  const argumentsList: string[] = [];
  let token = "";
  let quote = "";
  for (let index = 0; index < text.length; index++) {
    const current = text[index];
    if (quote) {
      if (current === quote) quote = "";
      else if (current === "\\" && text[index + 1] === quote)
        token += text[++index];
      else token += current;
    } else if (
      current === '"' ||
      (current === "'" &&
        !(
          /[\d=]$/.test(token) &&
          /^(?:s?[bohd][0-9a-fxz?_]|[01xz](?=\s|$))/i.test(
            text.slice(index + 1, index + 4),
          )
        ))
    ) {
      quote = current;
    } else if (/\s/.test(current)) {
      if (token) argumentsList.push(token);
      token = "";
    } else if (!token && (current === "#" || text.startsWith("//", index))) {
      const end = text.indexOf("\n", index);
      if (end < 0) break;
      index = end;
    } else if (!token && text.startsWith("/*", index)) {
      const end = text.indexOf("*/", index + 2);
      if (end < 0) throw Error("Unterminated comment in simulation filelist.");
      index = end + 1;
    } else {
      token += current;
    }
  }
  if (quote) throw Error("Unterminated quote in simulation filelist.");
  if (token) argumentsList.push(token);
  return argumentsList;
}

function vcsRebuildArguments(text: string) {
  const lines = text.trimEnd().split(/\r?\n/);
  if (
    lines[0] !== "#!/bin/sh -e" ||
    !lines[1]?.startsWith("# This file is automatically generated by VCS.") ||
    lines.slice(2, -1).some((line) => !line.startsWith("#"))
  )
    return undefined;
  const command = /^vcs((?: '[^'\r\n]*')+) 2>&1$/.exec(lines.at(-1) ?? "");
  if (!command) return undefined;
  return Array.from(command[1].matchAll(/'([^']*)'/g), (match) => match[1]);
}

async function readVcsMetadata(filename: string) {
  try {
    const attributes = await stat(filename, { bigint: true });
    return {
      text:
        attributes.isFile() && attributes.size <= 1024n * 1024n
          ? await readFile(filename, "utf8")
          : undefined,
      fingerprint: filelistFingerprint(attributes),
    };
  } catch (error) {
    const code = (error as NodeJS.ErrnoException).code;
    if (code === "ENOENT") return { fingerprint: null };
    if (code === "ENOTDIR" || code === "EACCES") return undefined;
    throw error;
  }
}

function vcsDesignMetadata(text: string) {
  const [header, ...lines] = text.split(/\r?\n/);
  if (header !== "rc file Version 1.0") return undefined;
  const design = lines.indexOf("[Design]");
  if (design === -1) return undefined;
  const attributes = new Map<string, string>();
  for (const line of lines.slice(design + 1)) {
    if (line.startsWith("[")) break;
    const field = /^(COMPILE_PATH|TOP)=(.*)$/.exec(line);
    if (!field) continue;
    if (attributes.has(field[1])) return undefined;
    attributes.set(field[1], field[2]);
  }
  const directory = attributes.get("COMPILE_PATH");
  const tops = attributes.get("TOP")?.trim().split(/\s+/);
  return {
    workingDirectory:
      directory && path.isAbsolute(directory) && !directory.includes("\0")
        ? path.resolve(directory)
        : undefined,
    topModules: tops?.every((name) => /^[A-Za-z_][\w$]*$/.test(name))
      ? tops
      : undefined,
  };
}

interface VcsRebuildInputs {
  args: string[];
  inputs: SimulationManifest["filelists"];
  topModules?: string[];
}

export async function discoverVcsRebuild(database: string) {
  database = path.resolve(database);
  if (!database.endsWith(".daidir")) return undefined;
  const filelist = path.join(database, "vcs_rebuild");
  const metadataPath = path.join(database, "simv.kdb");
  const [command, metadata] = await Promise.all([
    readVcsMetadata(filelist),
    readVcsMetadata(metadataPath),
  ]);
  const args = command?.text && vcsRebuildArguments(command.text);
  if (!args) return undefined;
  const outputIndex = args.lastIndexOf("-o");
  const output = outputIndex === -1 ? "simv" : args[outputIndex + 1];
  if (!output || /^[+-]/.test(output)) return undefined;
  const expected = database.slice(0, -".daidir".length);
  const design = metadata?.text ? vcsDesignMetadata(metadata.text) : undefined;
  let directory = design?.workingDirectory;
  if (!directory || path.resolve(directory, output) !== expected) {
    if (path.isAbsolute(output)) return undefined;
    directory = path.dirname(database);
    while (path.resolve(directory, output) !== expected) {
      const parent = path.dirname(directory);
      if (directory === parent) return undefined;
      directory = parent;
    }
  }
  const rebuild: VcsRebuildInputs = {
    args,
    inputs: [{ path: filelist, fingerprint: command.fingerprint }],
    topModules: design?.topModules,
  };
  if (metadata)
    rebuild.inputs.push({
      path: metadataPath,
      fingerprint: metadata.fingerprint,
    });
  return { filelist, workingDirectory: directory, rebuild };
}

function libraryMapRules(
  text: string,
  filename: string,
  diagnostics: Set<string>,
) {
  const tokens =
    text
      .match(/\/\/[^\r\n]*|\/\*[\s\S]*?\*\/|"(?:\\.|[^"\\])*"|[,;]|[^\s",;]+/g)
      ?.filter((token) => !token.startsWith("//") && !token.startsWith("/*")) ??
    [];
  const rules: { name: string; pattern: string; priority: number }[] = [];
  for (let index = 0; index < tokens.length; ) {
    const declaration = tokens[index++];
    if (declaration === "config") {
      const end = tokens.indexOf("endconfig", index);
      if (end < 0)
        diagnostics.add("Unterminated configuration block in " + filename);
      index = end < 0 ? tokens.length : end + 1;
      continue;
    }
    const declarationEnd = tokens.indexOf(";", index);
    const operands = tokens.slice(
      index,
      declarationEnd < 0 ? undefined : declarationEnd,
    );
    index = declarationEnd < 0 ? tokens.length : declarationEnd + 1;
    const [name, ...paths] = operands;
    if (
      declaration !== "library" ||
      declarationEnd < 0 ||
      !/^[A-Za-z_][\w$]*$/.test(name ?? "") ||
      !paths.length ||
      paths.length % 2 === 0 ||
      !paths.every((token, i) =>
        i % 2 ? token === "," : token !== "," && !token.startsWith("-"),
      )
    ) {
      diagnostics.add(
        "Unsupported library map declaration " +
          declaration +
          " in " +
          filename,
      );
      continue;
    }
    for (const token of paths.filter((_, i) => i % 2 === 0)) {
      const spec = token.startsWith('"')
        ? token.slice(1, -1).replace(/\\"/g, '"')
        : token;
      const directory = spec.endsWith("/");
      const pattern = path.posix.normalize(spec).replace(/\/$/, "") || "/";
      rules.push({
        name,
        pattern,
        priority: directory
          ? 2
          : /[*?]/.test(path.posix.basename(pattern))
            ? 1
            : 0,
      });
    }
  }
  return rules;
}

function libraryPatternMatches(file: string, pattern: string) {
  let source = 0;
  let rule = 0;
  let star = -1;
  let retry = 0;
  while (source < file.length) {
    if (pattern[rule] === "*") {
      star = rule++;
      retry = source;
    } else if (pattern[rule] === "?" || pattern[rule] === file[source]) {
      rule++;
      source++;
    } else if (star >= 0) {
      rule = star + 1;
      source = ++retry;
    } else {
      return false;
    }
  }
  while (pattern[rule] === "*") rule++;
  return rule === pattern.length;
}

export interface ElaboratedLibrarySources {
  kind: "verilator" | "kdb";
  files: () => readonly string[] | Promise<readonly string[]>;
}

export async function readSimulationFilelist(
  filename: string,
  workingDirectory: string,
  librarySources?: ElaboratedLibrarySources,
  rebuild?: VcsRebuildInputs,
) {
  const manifest: SimulationManifest = {
    schemaVersion: 1,
    filelist: path.resolve(filename),
    workingDirectory: path.resolve(workingDirectory),
    filelists: [],
    sourceFingerprints: [],
    sources: [],
    libraryFiles: [],
    resolvedLibraryFiles: [],
    includeDirectories: [],
    defines: [],
    topModules: [],
    parameterOverrides: [],
    unsupported: [],
  };
  const active = new Set<string>();
  const sourceHashes = new Map<string, string | undefined>();
  const diagnostics = new Set<string>();
  const parameterOptions: { flag: "-G" | "-pvalue+"; value: string }[] = [];
  const listedUnits: {
    files: SimulationManifest["sources"];
    includeDirectories: string[];
    defines: string[];
  }[] = [];
  let filesRead = 0;
  let singleUnit = false;
  let usesLibrarySearch = false;
  const libraryDirectories: string[] = [];
  const libraryExtensions = new Set<string>();

  function resolveInputPath(argument: string, base: string, filelist: string) {
    let missing = false;
    const expanded = argument.replace(
      /\$(?:([A-Za-z_]\w*)|\{([A-Za-z_]\w*)\}|\(([A-Za-z_]\w*)\))/g,
      (_match, bare, braced, parenthesized) => {
        const name = bare ?? braced ?? parenthesized;
        const value = process.env[name];
        if (value) return value;
        diagnostics.add("Missing path variable " + name + " in " + filelist);
        missing = true;
        return "";
      },
    );
    return missing ? undefined : path.resolve(base, expanded);
  }

  let sourceCount = 0;
  let workLibrary = "work";
  const sourceLibraries = new Map<string, string>();
  const libraryMaps = new Map<string, string>();
  async function addSource(
    source: string,
    files: SimulationManifest["sources"],
    library = workLibrary,
  ) {
    if (++sourceCount > 16384)
      throw Error("Simulation filelist expands to more than 16384 sources.");
    if (!sourceHashes.has(source)) {
      let hash: string | undefined;
      let fingerprint: string | null = null;
      try {
        const attributes = await stat(source, { bigint: true });
        fingerprint = filelistFingerprint(attributes);
        if (attributes.isFile() && attributes.size <= 16n * 1024n * 1024n)
          hash = createHash("sha256")
            .update(await readFile(source))
            .digest("hex");
      } catch (error) {
        if ((error as NodeJS.ErrnoException).code !== "ENOENT") throw error;
      }
      if (!hash) diagnostics.add("Unread or missing source " + source);
      sourceHashes.set(source, hash);
      manifest.sourceFingerprints.push({ path: source, fingerprint });
    }
    files.push({
      path: source,
      sha256: sourceHashes.get(source),
    });
    const previous = sourceLibraries.get(source);
    if (previous && previous !== library)
      throw Error("Source appears in multiple named libraries " + source);
    sourceLibraries.set(source, library);
  }

  async function readList(
    filename: string,
    base: string,
    unit?: (typeof listedUnits)[number],
  ) {
    if (++filesRead > 128)
      throw Error(
        "Simulation filelist nesting or expansion exceeds 128 reads.",
      );
    const identity = await realpath(filename).catch(
      (error: NodeJS.ErrnoException) => {
        if (error.code !== "ENOENT" || !active.size) throw error;
        return undefined;
      },
    );
    if (!identity) {
      manifest.filelists.push({ path: filename, fingerprint: null });
      diagnostics.add("Missing nested simulation filelist " + filename);
      return;
    }
    if (active.has(identity))
      throw Error("Cyclic simulation filelist " + filename);
    const buildCommand = active.size === 0 ? rebuild : undefined;
    active.add(identity);
    try {
      let args: string[];
      if (buildCommand) {
        args = buildCommand.args;
        manifest.filelists.push(...buildCommand.inputs);
      } else {
        const attributes = await stat(identity, { bigint: true });
        if (!attributes.isFile() || attributes.size > 2n * 1024n * 1024n)
          throw Error("Simulation filelist is too large " + filename);
        manifest.filelists.push({
          path: filename,
          fingerprint: filelistFingerprint(attributes),
        });
        args = filelistArguments(await readFile(identity, "utf8"));
      }
      const preprocess = unit ?? manifest;
      for (let index = 0; index < args.length; index++) {
        const arg = args[index];
        const option = (flag: string) => {
          const value = args[++index];
          if (!value || value.startsWith("-") || value.startsWith("+")) {
            throw Error("Missing value for " + flag + " in " + filename);
          }
          return value;
        };
        if (buildCommand && ["-o", "-l", "-Mdir", "-j"].includes(arg)) {
          option(arg);
        } else if (
          buildCommand &&
          (["-full64", "-64bit", "-kdb", "-sverilog"].includes(arg) ||
            /^-debug_(?:access|region)(?:\+.*)?$/.test(arg))
        ) {
          continue;
        } else if (!unit && (arg === "-f" || arg === "-F")) {
          const nested = resolveInputPath(option(arg), base, filename);
          if (nested)
            await readList(
              nested,
              arg === "-F" ? path.dirname(nested) : manifest.workingDirectory,
            );
        } else if (!unit && arg === "-C") {
          const name = resolveInputPath(option(arg), base, filename);
          if (!name) continue;
          const entry = { files: [], includeDirectories: [], defines: [] };
          await readList(name, path.dirname(name), entry);
          if (entry.files.length) listedUnits.push(entry);
        } else if (arg.startsWith("+incdir+")) {
          for (const name of arg.slice(8).split("+").filter(Boolean)) {
            const directory = resolveInputPath(name, base, filename);
            if (directory) preprocess.includeDirectories.push(directory);
          }
        } else if (arg === "-I" || arg.startsWith("-I")) {
          const directory = resolveInputPath(
            arg.length === 2 ? option(arg) : arg.slice(2),
            base,
            filename,
          );
          if (directory) preprocess.includeDirectories.push(directory);
        } else if (arg.startsWith("+define+")) {
          preprocess.defines.push(...arg.slice(8).split("+").filter(Boolean));
        } else if (arg === "-D" || arg.startsWith("-D")) {
          preprocess.defines.push(
            arg.length === 2 ? option(arg) : arg.slice(2),
          );
        } else if (unit && arg === "--include-directory") {
          const directory = resolveInputPath(option(arg), base, filename);
          if (directory) unit.includeDirectories.push(directory);
        } else if (unit && arg === "--define-macro") {
          unit.defines.push(option(arg));
        } else if (
          unit &&
          (arg === "--library" || arg === "-f" || arg === "-F" || arg === "-C")
        ) {
          diagnostics.add(arg + " " + option(arg) + " in " + filename);
        } else if (unit && /^[+-]/.test(arg)) {
          diagnostics.add(arg + " in " + filename);
        } else if (arg === "-top" || arg === "--top-module") {
          manifest.topModules.push(option(arg));
        } else if (arg === "-G" || arg.startsWith("-G")) {
          parameterOptions.push({
            flag: "-G",
            value: arg === "-G" ? option(arg) : arg.slice(2),
          });
        } else if (arg === "--single-unit") {
          singleUnit = true;
        } else if (arg === "-v") {
          const name = option(arg);
          const source = resolveInputPath(name, base, filename);
          if (source && /\.(?:sv|v)$/i.test(source))
            await addSource(source, manifest.libraryFiles);
          else if (source) diagnostics.add("-v " + name);
        } else if (arg === "-y") {
          const name = option(arg);
          const directory = resolveInputPath(name, base, filename);
          if (!directory) continue;
          if (librarySources) {
            usesLibrarySearch = true;
            libraryDirectories.push(directory);
            if (librarySources.kind === "verilator")
              manifest.includeDirectories.push(directory);
          } else diagnostics.add("-y " + name);
        } else if (arg.startsWith("+libext+") && librarySources) {
          usesLibrarySearch = true;
          for (const extension of arg.slice(8).split("+"))
            if (extension) libraryExtensions.add(extension);
        } else if (arg === "-work" || arg === "--work") {
          workLibrary = option(arg);
        } else if (arg === "-libmap" || arg === "--libmap") {
          const argument = option(arg);
          const file = resolveInputPath(
            argument,
            manifest.workingDirectory,
            filename,
          );
          if (file) libraryMaps.set(argument, file);
        } else if (arg.startsWith("-pvalue+")) {
          parameterOptions.push({
            flag: "-pvalue+",
            value: arg === "-pvalue+" ? option(arg) : arg.slice(8),
          });
        } else if (/^[+-]/.test(arg)) {
          diagnostics.add(arg);
        } else {
          const source = resolveInputPath(arg, base, filename);
          if (!source) continue;
          if (!/\.(?:sv|v|svh|vh|svi)$/i.test(source)) {
            diagnostics.add(arg);
            continue;
          }
          await addSource(
            source,
            unit?.files ?? manifest.sources,
            unit ? "work" : workLibrary,
          );
        }
      }
    } finally {
      active.delete(identity);
    }
  }

  await readList(manifest.filelist, manifest.workingDirectory);
  if (rebuild?.topModules && !manifest.topModules.length)
    manifest.topModules.push(...rebuild.topModules);
  const selectedTops = new Set(manifest.topModules);
  const vcsParameters = new Map<string, number>();
  const unverifiedPaths = new Map<string, string>();
  for (const { flag, value } of parameterOptions) {
    if (flag === "-G" && /^[A-Za-z_][\w$]*=.+$/.test(value)) {
      manifest.parameterOverrides.push(value);
      continue;
    }
    if (flag === "-pvalue+") {
      const match =
        /^([A-Za-z_][\w$]*)\.((?:[A-Za-z_][\w$]*(?:\[-?\d+\])?\.)*[A-Za-z_][\w$]*)=(.+)$/.exec(
          value,
        );
      if (match && selectedTops.has(match[1])) {
        const [, top, parameterPath, expression] = match;
        const canonicalPath = parameterPath.replace(
          /\[(-?)0*(\d+)\]/g,
          (_, sign: string, digits: string) =>
            "[" + (digits === "0" ? "" : sign) + digits + "]",
        );
        const target =
          selectedTops.size === 1 && !parameterPath.includes(".")
            ? parameterPath
            : top + "." + canonicalPath;
        // VCS applies the last assignment, while Slang keeps the first.
        const index =
          vcsParameters.get(target) ?? manifest.parameterOverrides.length;
        vcsParameters.set(target, index);
        manifest.parameterOverrides[index] = target + "=" + expression;
        // VCS simulation accepts noncanonical indices, but its KDB elaboration
        // can ignore the corresponding override.
        if (parameterPath !== canonicalPath)
          unverifiedPaths.set(target, top + "." + parameterPath);
        else unverifiedPaths.delete(target);
        continue;
      }
    }
    diagnostics.add(flag + (flag === "-G" ? " " : "") + value);
  }
  if (unverifiedPaths.size) {
    manifest.unverifiedVcsParameterPaths = [...unverifiedPaths.values()];
    for (const [canonicalPath, path] of unverifiedPaths)
      diagnostics.add(
        "VCS KDB may omit parameter override " +
          path +
          " (normalized to " +
          canonicalPath +
          ")",
      );
  }
  if (singleUnit || listedUnits.length) {
    const roots = manifest.sources.map(({ path }) => path);
    const groups =
      singleUnit && roots.length ? [roots] : roots.map((file) => [file]);
    manifest.compilationUnits = groups.concat(
      listedUnits.map((entry) => entry.files.map(({ path }) => path)),
    );
    if (listedUnits.length) {
      manifest.compilationUnitOptions = [
        ...groups.map(() => ({})),
        ...listedUnits.map((unit) => ({
          defines: unit.defines,
          include_dirs: unit.includeDirectories,
        })),
      ];
      manifest.sources.push(...listedUnits.flatMap((unit) => unit.files));
    }
  }
  if (libraryMaps.size) {
    if (filesRead + libraryMaps.size > 128)
      throw Error(
        "Simulation filelist and library map expansion exceeds 128 reads.",
      );
    const rules = [];
    const maps = [...libraryMaps.entries()].sort(([left], [right]) =>
      left < right ? -1 : left > right ? 1 : 0,
    );
    manifest.libraryMaps = [];
    for (const [, file] of maps) {
      try {
        const identity = await realpath(file);
        const info = await stat(identity, { bigint: true });
        if (!info.isFile() || info.size > 2n * 1024n * 1024n)
          throw Error("Invalid or oversized library map " + file);
        manifest.filelists.push({
          path: file,
          fingerprint: filelistFingerprint(info),
        });
        if (/\.map$/i.test(file)) manifest.libraryMaps.push(file);
        else
          diagnostics.add(
            "VIDE requires a .map file for library-map source " + file,
          );
        const base = await realpath(path.dirname(file));
        for (const rule of libraryMapRules(
          await readFile(identity, "utf8"),
          file,
          diagnostics,
        ))
          rules.push({ ...rule, base });
        if (rules.length > 4096)
          throw Error("Library maps exceed 4096 file patterns.");
      } catch (error) {
        if ((error as NodeJS.ErrnoException).code !== "ENOENT") throw error;
        manifest.filelists.push({ path: file, fingerprint: null });
        diagnostics.add("Missing library map " + file);
      }
    }
    rules.sort((left, right) => left.priority - right.priority);
    for (const { path: file } of manifest.sources) {
      if (sourceLibraries.get(file) !== "work") continue;
      const absolute = await realpath(file).catch(() => file);
      const match = rules.find((rule) => {
        const relative = path
          .relative(rule.base, absolute)
          .split(path.sep)
          .join("/");
        return libraryPatternMatches(
          rule.priority === 2 ? path.posix.dirname(relative) : relative,
          rule.pattern,
        );
      });
      if (match) sourceLibraries.set(file, match.name);
    }
  }
  if (usesLibrarySearch && librarySources) {
    let elaboratedFiles: readonly string[] = [];
    try {
      elaboratedFiles = await librarySources.files();
    } catch {
      diagnostics.add(
        "Library source locations are unavailable from " +
          (librarySources.kind === "kdb" ? "VCS KDB" : "Verilator elaboration"),
      );
    }
    const canonical = (file: string) => realpath(file).catch(() => file);
    const loaded = new Set(
      await Promise.all([...sourceHashes.keys()].map(canonical)),
    );
    const directories = new Set(
      await Promise.all(
        (librarySources.kind === "kdb"
          ? libraryDirectories
          : [manifest.workingDirectory, ...manifest.includeDirectories]
        ).map(canonical),
      ),
    );
    for (const file of elaboratedFiles) {
      const identity = await canonical(file);
      if (loaded.has(identity)) continue;
      if (
        !directories.has(path.dirname(identity)) ||
        !/\.(?:sv|v)$/i.test(identity) ||
        (librarySources.kind === "kdb" &&
          libraryExtensions.size &&
          !libraryExtensions.has(path.extname(file)))
      ) {
        if (librarySources.kind === "verilator")
          diagnostics.add("Unmapped Verilator library source " + file);
        continue;
      }
      await addSource(file, manifest.libraryFiles, "work");
      loaded.add(identity);
      manifest.resolvedLibraryFiles.push(file);
    }
  }
  if (
    !(await simulationFilelistsCurrent([
      ...manifest.filelists,
      ...manifest.sourceFingerprints,
    ]))
  )
    throw Error(
      "The simulation inputs changed while the filelist was being read.",
    );
  if ([...sourceLibraries.values()].some((name) => name !== "work")) {
    manifest.sourceLibraries = [...sourceLibraries]
      .filter(([, name]) => name !== "work")
      .map(([path, name]) => ({ path, name }));
  }
  if (
    manifest.compilationUnits?.some(
      (unit) =>
        new Set(unit.map((file) => sourceLibraries.get(file) ?? "work")).size >
        1,
    )
  )
    throw Error("A compilation unit spans multiple named source libraries.");
  manifest.unsupported = [...diagnostics];
  return manifest;
}

function compilationUnitOptionsLine(
  options: SimulationManifest["compilationUnitOptions"],
) {
  if (!options) return [];
  const entries = options.map(
    (unit) =>
      "{ defines = " +
      JSON.stringify(unit.defines ?? []) +
      ", include_dirs = " +
      JSON.stringify(unit.include_dirs ?? []) +
      " }",
  );
  return ["compilation_unit_options = [" + entries.join(", ") + "]"];
}

function sourceLibrariesLine(libraries: SimulationManifest["sourceLibraries"]) {
  return libraries?.length
    ? [
        "source_libraries = [" +
          libraries
            .map(
              ({ path, name }) =>
                "{ path = " +
                JSON.stringify(path) +
                ", name = " +
                JSON.stringify(name) +
                " }",
            )
            .join(", ") +
          "]",
      ]
    : [];
}

export function previewVideManifest(manifest: SimulationManifest) {
  const comment = (value: string) => value.replace(/[\r\n]/g, " ");
  const notes = [
    "# Generated from " + comment(manifest.filelist),
    "# Simulator working directory " + comment(manifest.workingDirectory),
    ...manifest.unsupported.map((message) => "# Unmapped " + comment(message)),
  ];
  return notes.join("\n") + "\n\n" + traceVideManifest(manifest);
}

export function traceVideManifest(
  manifest: Pick<
    SimulationManifest,
    | "sources"
    | "compilationUnits"
    | "compilationUnitOptions"
    | "libraryFiles"
    | "libraryMaps"
    | "sourceLibraries"
    | "includeDirectories"
    | "defines"
    | "topModules"
    | "parameterOverrides"
  >,
) {
  const entries = {
    source_files: manifest.sources.map(({ path }) => path),
    ...(manifest.compilationUnits
      ? { compilation_units: manifest.compilationUnits }
      : {}),
    ...(manifest.libraryFiles.length
      ? { library_files: manifest.libraryFiles.map(({ path }) => path) }
      : {}),
    ...(manifest.libraryMaps?.length
      ? { library_maps: manifest.libraryMaps }
      : {}),
    include_dirs: manifest.includeDirectories,
    defines: manifest.defines,
    top_modules: manifest.topModules,
    parameter_overrides: manifest.parameterOverrides,
  };
  return (
    Object.entries(entries)
      .map(([key, value]) => key + " = " + JSON.stringify(value))
      .concat(
        compilationUnitOptionsLine(manifest.compilationUnitOptions),
        sourceLibrariesLine(manifest.sourceLibraries),
      )
      .join("\n") + "\n"
  );
}
