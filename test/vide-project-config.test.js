test("VCS rebuild metadata discovers the compile directory and keeps build inputs", async (t) => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), "vide-vcs-rebuild-"));
  t.after(() => fs.rm(root, { recursive: true, force: true }));
  const database = path.join(root, "build", "simv.daidir");
  const script = path.join(database, "vcs_rebuild");
  await fs.mkdir(database, { recursive: true });
  await fs.writeFile(path.join(root, "tb.sv"), "module tb; endmodule\n");
  await fs.writeFile(path.join(root, "run.f"), "tb.sv\n");
  const rebuild = "#!/bin/sh -e\n# This file is automatically generated by VCS.\n" +
    "vcs '-full64' '-kdb' '+define+MODE=1' '-top' 'tb' '-f' 'run.f' '-o' 'build/simv' 2>&1\n";
  await fs.writeFile(script, rebuild);
  const selection = await discoverVcsRebuild(database);
  assert.equal(selection.workingDirectory, root);
  const manifest = await readSimulationFilelist(
    selection.filelist, selection.workingDirectory, undefined, selection.rebuild,
  );
  assert.deepEqual(manifest.sources.map(({ path: file }) => file), [path.join(root, "tb.sv")]);
  assert.deepEqual(manifest.defines, ["MODE=1"]);
  assert.deepEqual(manifest.topModules, ["tb"]);
  assert.deepEqual(manifest.unsupported, []);
  assert.equal(await simulationFilelistsCurrent(manifest.filelists), true);
  await fs.writeFile(path.join(database, "simv.kdb"),
    `rc file Version 1.0\n[Design]\nCOMPILE_PATH=${root}\nTOP=other\n`);
  assert.equal(await simulationFilelistsCurrent(manifest.filelists), false);
  const withMetadata = await discoverVcsRebuild(database);
  const explicitTop = await readSimulationFilelist(
    withMetadata.filelist, withMetadata.workingDirectory, undefined, withMetadata.rebuild,
  );
  assert.deepEqual(explicitTop.topModules, ["tb"]);
  assert.equal(await simulationFilelistsCurrent(explicitTop.filelists), true);
  await fs.writeFile(script, rebuild + "printf another-command\n");
  assert.equal(await discoverVcsRebuild(database), undefined);
  assert.equal(await simulationFilelistsCurrent(explicitTop.filelists), false);
  await assert.rejects(readSimulationFilelist(
    withMetadata.filelist, withMetadata.workingDirectory, undefined, withMetadata.rebuild,
  ), /simulation inputs changed while the filelist was being read/i);
});

test("VCS rebuild resolves relative inputs from the recorded compile directory", async (t) => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), "vide-vcs-compile-path-"));
  t.after(() => fs.rm(root, { recursive: true, force: true }));
  const compileDirectory = path.join(root, "compile area");
  const output = path.join(root, "artifacts", "simv");
  const database = output + ".daidir";
  const script = path.join(database, "vcs_rebuild");
  await Promise.all([
    fs.mkdir(database, { recursive: true }),
    fs.mkdir(path.join(compileDirectory, "lists"), { recursive: true }),
  ]);
  const writeRebuild = (outputArgument) => fs.writeFile(
    script,
    "#!/bin/sh -e\n# This file is automatically generated by VCS.\n" +
    `vcs '-kdb' '-sverilog' '-F' 'lists/build.f' '-pvalue+tb.WIDTH=4' '-o' '${outputArgument}' 2>&1\n`,
  );
  await Promise.all([
    writeRebuild(output),
    fs.writeFile(path.join(compileDirectory, "tb.sv"), "module tb; endmodule\n"),
    fs.writeFile(path.join(compileDirectory, "lists", "build.f"), "+incdir+../include\n../tb.sv\n"),
  ]);
  assert.equal(await discoverVcsRebuild(database), undefined);
  await fs.writeFile(
    path.join(database, "simv.kdb"),
    `rc file Version 1.0\n[Design]\nCOMPILE_PATH=${compileDirectory}\nTOP=tb \n[vcs]\nCOMPILE_PATH=/unused\n`,
  );
  for (const outputArgument of [output, "../artifacts/simv"]) {
    await writeRebuild(outputArgument);
    const selection = await discoverVcsRebuild(database);
    assert.equal(selection.workingDirectory, compileDirectory);
    const manifest = await readSimulationFilelist(
      selection.filelist, selection.workingDirectory, undefined, selection.rebuild,
    );
    assert.deepEqual(manifest.sources.map(({ path: file }) => file), [path.join(compileDirectory, "tb.sv")]);
    assert.deepEqual(manifest.includeDirectories, [path.join(compileDirectory, "include")]);
    assert.deepEqual(manifest.topModules, ["tb"]);
    assert.deepEqual(manifest.parameterOverrides, ["WIDTH=4"]);
    assert.ok(manifest.filelists.some(({ path: file }) => file === path.join(database, "simv.kdb")));
    assert.deepEqual(manifest.unsupported, []);
  }
});

test("simulation filelists preserve nested path semantics, quoting and build inputs", async (t) => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), "vide-filelist-"));
  t.after(() => fs.rm(root, { recursive: true, force: true }));
  const buildEnvironment = {
    WAVE_VIDE_TEST_LIST_DIR: "sub",
    WAVE_VIDE_TEST_INCLUDE_DIR: "include files",
    WAVE_VIDE_TEST_TB: "tb.sv",
    WAVE_VIDE_TEST_UNSET_PATH: undefined,
  };
  for (const [name, value] of Object.entries(buildEnvironment)) {
    const original = process.env[name];
    if (value === undefined) delete process.env[name];
    else process.env[name] = value;
    t.after(() => {
      if (original === undefined) delete process.env[name];
      else process.env[name] = original;
    });
  }
  await fs.mkdir(path.join(root, "sub"));
  const write = (name, value) => fs.writeFile(path.join(root, name), value);
  await Promise.all([
    write("tb.sv", "module tb; endmodule\n"),
    write("sub/leaf.sv", "module leaf; endmodule\n"),
    write("sub/other.sv", "module other; endmodule\n"),
    write("sub/cells.v", "module cells; endmodule\n"),
    write("sources.f", [
      "# testbench build",
      "/* sources follow */ -f $WAVE_VIDE_TEST_LIST_DIR/working.f",
      '-F "${WAVE_VIDE_TEST_LIST_DIR}/relative list.f" +incdir+$(WAVE_VIDE_TEST_INCLUDE_DIR)',
      "-f ${WAVE_VIDE_TEST_UNSET_PATH}/optional.f",
      "+define+MODE=1 -D MODE2 --top-module tb",
      "-GWIDTH=4 -G MASK=16'h00ff -G DEFAULT='0 -G sub.WIDTH=8 // parameter overrides",
    ].join("\n")),
    write("sub/working.f", "$WAVE_VIDE_TEST_TB\n"),
    write("sub/relative list.f", 'leaf.sv "other.sv" -v cells.v\n'),
  ]);
  const manifest = await readSimulationFilelist(path.join(root, "sources.f"), root);
  assert.deepEqual(manifest.sources.map(({ path: name }) => path.relative(root, name)), [
    "tb.sv",
    path.join("sub", "leaf.sv"),
    path.join("sub", "other.sv"),
  ]);
  assert.ok(manifest.sources.every(({ sha256 }) => /^[0-9a-f]{64}$/.test(sha256)));
  const library = path.join(root, "sub", "cells.v");
  assert.deepEqual(manifest.libraryFiles.map(({ path: file }) => file), [library]);
  assert.match(manifest.libraryFiles[0].sha256, /^[0-9a-f]{64}$/);
  assert.ok(traceVideManifest(manifest).includes("library_files = " + JSON.stringify([library])));
  assert.deepEqual(manifest.includeDirectories, [path.join(root, "include files")]);
  assert.deepEqual(manifest.defines, ["MODE=1", "MODE2"]);
  assert.deepEqual(manifest.topModules, ["tb"]);
  assert.deepEqual(manifest.parameterOverrides, ["WIDTH=4", "MASK=16'h00ff", "DEFAULT='0"]);
  assert.deepEqual(manifest.unsupported, [
    "Missing path variable WAVE_VIDE_TEST_UNSET_PATH in " + path.join(root, "sources.f"),
    "-G sub.WIDTH=8",
  ]);
  const toml = previewVideManifest(manifest);
  assert.equal(toml.split("\n\n")[1], traceVideManifest(manifest));
  assert.match(toml, /parameter_overrides = \["WIDTH=4","MASK=16'h00ff","DEFAULT='0"\]/);
  assert.match(toml, /# Unmapped -G sub\.WIDTH=8/);
  assert.equal(await simulationFilelistsCurrent(manifest.filelists), true);

  const nested = path.join(root, "sub", "relative list.f");
  const original = await fs.stat(nested);
  const replacement = path.join(root, "sub", "replacement.f");
  await fs.writeFile(replacement, 'leaf.sv "other.sv" -v cells.v\n');
  await fs.utimes(replacement, original.atime, original.mtime);
  await fs.rename(replacement, nested);
  assert.equal(await simulationFilelistsCurrent(manifest.filelists), false);

  await write("recursive.f", "-f recursive.f\n");
  await assert.rejects(readSimulationFilelist(path.join(root, "recursive.f"), root), /Cyclic simulation filelist/);
});

test("missing generated lists preserve available sources and invalidate the config when created", async (t) => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), "vide-generated-list-"));
  t.after(() => fs.rm(root, { recursive: true, force: true }));
  const build = path.join(root, "build.f");
  const generated = path.join(root, "out", "generated.f");
  const module = path.join(root, "out", "generated.sv");
  const tb = path.join(root, "tb.sv");
  await Promise.all([
    fs.writeFile(build, "-top tb -F out/generated.f tb.sv\n"),
    fs.writeFile(tb, "module tb; endmodule\n"),
  ]);
  await assert.rejects(readSimulationFilelist(generated, root), { code: "ENOENT" });
  const partial = await readSimulationFilelist(build, root);
  assert.deepEqual(partial.sources.map((source) => source.path), [tb]);
  assert.deepEqual(partial.topModules, ["tb"]);
  assert.deepEqual(partial.unsupported, ["Missing nested simulation filelist " + generated]);
  assert.match(previewVideManifest(partial), /# Unmapped Missing nested simulation filelist/);
  assert.equal(await simulationFilelistsCurrent(partial.filelists), true);

  await fs.mkdir(path.dirname(generated));
  await Promise.all([
    fs.writeFile(generated, "+incdir+include generated.sv\n"),
    fs.writeFile(module, "module generated; endmodule\n"),
  ]);
  assert.equal(await simulationFilelistsCurrent(partial.filelists), false);
  const restored = await readSimulationFilelist(build, root);
  assert.deepEqual(restored.sources.map((source) => source.path), [module, tb]);
  assert.deepEqual(restored.includeDirectories, [path.join(root, "out", "include")]);
  assert.deepEqual(restored.unsupported, []);
});

test("a generated compilation source can appear or change without modifying its filelist", async (t) => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), "vide-generated-source-"));
  t.after(() => fs.rm(root, { recursive: true, force: true }));
  const build = path.join(root, "build.f");
  const source = path.join(root, "generated.sv");
  await fs.writeFile(build, "generated.sv\n");
  const missing = await readSimulationFilelist(build, root);
  assert.deepEqual(missing.sourceFingerprints, [{ path: source, fingerprint: null }]);
  assert.equal(await simulationFilelistsCurrent(missing.sourceFingerprints), true);

  await fs.writeFile(source, "module generated; wire a; endmodule\n");
  assert.equal(await simulationFilelistsCurrent(missing.filelists), true);
  assert.equal(await simulationFilelistsCurrent(missing.sourceFingerprints), false);
  const present = await readSimulationFilelist(build, root);
  assert.deepEqual(present.unsupported, []);
  assert.equal(await simulationFilelistsCurrent(present.sourceFingerprints), true);

  const replacement = path.join(root, "replacement.sv");
  const original = await fs.stat(source);
  await fs.writeFile(replacement, "module generated; wire b; endmodule\n");
  await fs.utimes(replacement, original.atime, original.mtime);
  await fs.rename(replacement, source);
  assert.equal(await simulationFilelistsCurrent(present.filelists), true);
  assert.equal(await simulationFilelistsCurrent(present.sourceFingerprints), false);
});

test("library search uses the elaborated Verilator files and preserves unresolved inputs", async (t) => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), "vide-library-search-"));
  t.after(() => fs.rm(root, { recursive: true, force: true }));
  const lib = path.join(root, "lib");
  const shadow = path.join(root, "shadow");
  const filelist = path.join(root, "build.f");
  const source = path.join(lib, "cell.sv");
  const unlisted = path.join(root, "unlisted", "cell.sv");
  const primary = path.join(root, "top.sv");
  await Promise.all([
    fs.mkdir(lib),
    fs.mkdir(shadow),
    fs.writeFile(filelist, '-y lib +incdir+include -y shadow +libext+.sv+.v top.sv\n'),
    fs.writeFile(primary, "module top; endmodule\n"),
  ]);
  await Promise.all([
    fs.writeFile(source, "module cell; endmodule\n"),
    fs.writeFile(path.join(shadow, "cell.v"), "module cell; endmodule\n"),
  ]);

  const withoutDesign = await readSimulationFilelist(filelist, root);
  assert.deepEqual(withoutDesign.libraryFiles, []);
  assert.deepEqual(withoutDesign.unsupported, ["-y lib", "-y shadow", "+libext+.sv+.v"]);
  const withDesign = await readSimulationFilelist(filelist, root, {
    kind: "verilator",
    files: () => [primary, source, source, unlisted],
  });
  assert.deepEqual(withDesign.includeDirectories, [lib, path.join(root, "include"), shadow]);
  assert.deepEqual(withDesign.resolvedLibraryFiles, [source]);
  assert.deepEqual(withDesign.libraryFiles.map(({ path: file }) => file), [source]);
  assert.deepEqual(withDesign.unsupported, ["Unmapped Verilator library source " + unlisted]);
  await fs.writeFile(filelist, "-y lib +incdir+include -y shadow +libext+.sv top.sv\n");
  const withKdb = await readSimulationFilelist(filelist, root, {
    kind: "kdb",
    files: async () => [primary, source, path.join(shadow, "cell.v"), unlisted],
  });
  assert.deepEqual(withKdb.resolvedLibraryFiles, [source]);
  assert.deepEqual(withKdb.includeDirectories, [path.join(root, "include")]);
  assert.deepEqual(withKdb.unsupported, []);

  await fs.writeFile(filelist, "--single-unit top.sv lib/cell.sv -v shadow/cell.v\n");
  const grouped = await readSimulationFilelist(filelist, root);
  assert.deepEqual(grouped.compilationUnits, [[primary, source]]);
  assert.deepEqual(grouped.libraryFiles.map(({ path: file }) => file), [path.join(shadow, "cell.v")]);
  assert.ok(traceVideManifest(grouped).includes("compilation_units = " + JSON.stringify([[primary, source]])));

  await fs.writeFile(filelist, "-DGLOBAL=1 top.sv -C lib/one.f -C shadow/two.f\n");
  await fs.writeFile(path.join(lib, "one.f"), "+incdir+inc +define+UNIT=1 cell.sv\n");
  await fs.writeFile(path.join(shadow, "two.f"), "--include-directory inc --define-macro UNIT=0 cell.v\n");
  const separate = await readSimulationFilelist(filelist, root);
  assert.deepEqual(separate.defines, ["GLOBAL=1"]);
  assert.deepEqual(separate.includeDirectories, []);
  assert.deepEqual(separate.compilationUnits, [[primary], [source], [path.join(shadow, "cell.v")]]);
  assert.deepEqual(separate.compilationUnitOptions, [
    {},
    {defines: ["UNIT=1"], include_dirs: [path.join(lib, "inc")]},
    {defines: ["UNIT=0"], include_dirs: [path.join(shadow, "inc")]},
  ]);
  const unitToml = traceVideManifest(separate);
  assert.match(unitToml, /compilation_unit_options = \[\{ defines = \[\], include_dirs = \[\] \}/);
  assert.equal(previewVideManifest(separate).split("\n\n")[1], unitToml);

  await fs.writeFile(filelist, "top.sv -work positive lib/cell.sv --work negative -v shadow/cell.v -work work\n");
  const named = await readSimulationFilelist(filelist, root);
  assert.deepEqual(named.sourceLibraries, [
    { path: source, name: "positive" },
    { path: path.join(shadow, "cell.v"), name: "negative" },
  ]);
  assert.deepEqual(named.unsupported, []);
  assert.ok(traceVideManifest(named).includes('name = "positive"'));
});

test("VCS parameter overrides retain the explicitly selected testbench scope", async (t) => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), "vide-vcs-parameters-"));
  t.after(() => fs.rm(root, { recursive: true, force: true }));
  const filelist = path.join(root, "sources.f");
  const write = (name, value) => fs.writeFile(path.join(root, name), value);
  await Promise.all([
    write("tb.sv", "module tb #(parameter int WIDTH = 0); endmodule\n"),
    write("options.f", "-pvalue+tb.WIDTH=4 -pvalue+tb.dut.WIDTH=8 -pvalue+tb.sibling.WIDTH=2\n"),
  ]);
  const read = async (tops) => {
    await write("sources.f", [
      "-f options.f -pvalue+other.WIDTH=3",
      "-pvalue+tb.MASK=4'b1010 -pvalue+tb.WIDTH=6 -pvalue+tb.dut.WIDTH=9 -pvalue+tb.EMPTY= tb.sv",
      tops,
    ].join("\n"));
    return readSimulationFilelist(filelist, root);
  };
  const exact = await read("-top tb");
  assert.deepEqual(exact.parameterOverrides, ["WIDTH=6", "tb.dut.WIDTH=9", "tb.sibling.WIDTH=2", "MASK=4'b1010"]);
  assert.deepEqual(exact.unsupported, ["-pvalue+other.WIDTH=3", "-pvalue+tb.EMPTY="]);
  assert.match(traceVideManifest(exact), /parameter_overrides = \["WIDTH=6","tb.dut.WIDTH=9",/);

  const multipleTops = await read("-top tb -top other");
  assert.deepEqual(multipleTops.parameterOverrides, [
    "tb.WIDTH=6", "tb.dut.WIDTH=9", "tb.sibling.WIDTH=2", "other.WIDTH=3", "tb.MASK=4'b1010",
  ]);
  assert.deepEqual(multipleTops.unsupported, ["-pvalue+tb.EMPTY="]);

  for (const tops of ["", "-top absent"]) {
    const unresolved = await read(tops);
    assert.deepEqual(unresolved.parameterOverrides, []);
    assert.ok(unresolved.unsupported.includes("-pvalue+tb.WIDTH=4"));
  }
});

test("VCS overrides use the last value for each elaborated array index", async (t) => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), "vide-indexed-parameters-"));
  t.after(() => fs.rm(root, { recursive: true, force: true }));
  const filelist = path.join(root, "sources.f");
  await fs.writeFile(filelist, [
    "-top tb",
    "-pvalue+tb.bank[1].MODE=2",
    "-pvalue+tb.lanes[-01].dut.MODE=3",
    "-pvalue+tb.bank[01].MODE=4",
    "-pvalue+tb.bank[2].MODE=5",
    "-pvalue+tb.bank[02].MODE=6",
    "-pvalue+tb.bank[2].MODE=5",
    "-pvalue+tb.bank[*].MODE=6",
    "-pvalue+tb.MODE[1]=1",
  ].join("\n"));
  const manifest = await readSimulationFilelist(filelist, root);
  assert.deepEqual(manifest.parameterOverrides, [
    "tb.bank[1].MODE=4", "tb.lanes[-1].dut.MODE=3", "tb.bank[2].MODE=5",
  ]);
  assert.deepEqual(manifest.unverifiedVcsParameterPaths, ["tb.lanes[-01].dut.MODE", "tb.bank[01].MODE"]);
  assert.deepEqual(manifest.unsupported, [
    "-pvalue+tb.bank[*].MODE=6", "-pvalue+tb.MODE[1]=1",
    "VCS KDB may omit parameter override tb.lanes[-01].dut.MODE (normalized to tb.lanes[-1].dut.MODE)",
    "VCS KDB may omit parameter override tb.bank[01].MODE (normalized to tb.bank[1].MODE)",
  ]);
  assert.match(traceVideManifest(manifest), /"tb\.lanes\[-1\]\.dut\.MODE=3"/);
});

test("Verilator library maps resolve precedence and invalidate cached configuration", async (t) => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), "vide-libmap-"));
  t.after(() => fs.rm(root, { recursive: true, force: true }));
  for (const directory of ["rtl", "options", "maps"])
    await fs.mkdir(path.join(root, directory));
  const filelist = path.join(root, "options", "build.f");
  const outer = path.join(root, "build.f");
  const map = path.join(root, "maps", "design.map");
  const missing = path.join(root, "maps", "optional.map");
  const source = (name) => path.join(root, "rtl", name);
  await Promise.all([
    fs.writeFile(outer, "-F options/build.f\n"),
    fs.writeFile(filelist, [
      "-libmap maps/design.map -libmap maps/optional.map",
      "../rtl/main.sv ../rtl/exact.sv ../rtl/dir.v",
      "-work override ../rtl/override.sv -work work -v ../rtl/library.sv",
    ].join("\n")),
    fs.writeFile(map, [
      "/* Directories apply after wildcards. */",
      "library fallback ../rtl/;",
      "library glob ../rtl/*.sv;",
      "library exact ../rtl/exact.sv, ../rtl/unused.v;",
    ].join("\n")),
    ...["main.sv", "exact.sv", "dir.v", "override.sv", "library.sv", "unused.v"]
      .map((name) => fs.writeFile(source(name), "module cell; endmodule\n")),
  ]);
  const initial = await readSimulationFilelist(outer, root);
  assert.deepEqual(initial.libraryMaps, [map]);
  assert.deepEqual(initial.sourceLibraries, [
    { path: source("main.sv"), name: "glob" },
    { path: source("exact.sv"), name: "exact" },
    { path: source("dir.v"), name: "fallback" },
    { path: source("override.sv"), name: "override" },
  ]);
  assert.deepEqual(initial.unsupported, ["Missing library map " + missing]);
  assert.equal(await simulationFilelistsCurrent(initial.filelists), true);
  await fs.writeFile(missing, "library other ../rtl/dir.v;\n");
  assert.equal(await simulationFilelistsCurrent(initial.filelists), false);
  const reloaded = await readSimulationFilelist(outer, root);
  assert.deepEqual(reloaded.unsupported, []);
  assert.deepEqual(reloaded.libraryMaps, [map, missing]);
  assert.equal(reloaded.sourceLibraries.find(({ path: file }) => file === source("dir.v")).name, "other");
});
